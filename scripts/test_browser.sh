#!/usr/bin/env bash
# Run only against an isolated marksix_test database; both child services are owned here.
set -euo pipefail
project_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
: "${TEST_DATABASE_URL:?Set the isolated marksix_test database URL}"
: "${TEST_ADMIN_PASSWORD:?Set the disposable test password}"
[[ "$TEST_DATABASE_URL" == */marksix_test ]] || { echo 'Only marksix_test may be used' >&2; exit 1; }
mkdir -p "$project_root/test-results/coverage"
cd "$project_root/backend"
export CARGO_TARGET_DIR="$project_root/backend/target/llvm-cov-target"
# The output is generated by the pinned, locally installed coverage tool.
coverage_environment="$(cargo llvm-cov show-env --export-prefix)"
eval "$coverage_environment"
cargo build --locked --example e2e_server
server_pid=''
vite_pid=''
cleanup() {
  result=$?
  trap - EXIT
  for owned_pid in "$vite_pid" "$server_pid"; do
    if [[ -n "$owned_pid" ]]; then
      kill -TERM "$owned_pid" 2>/dev/null || true
      wait "$owned_pid" 2>/dev/null || true
    fi
  done
  (cd "$project_root/backend" && cargo llvm-cov report --json --output-path "$project_root/test-results/coverage/backend.json") || result=1
  exit "$result"
}
trap cleanup EXIT
"$CARGO_TARGET_DIR/debug/examples/e2e_server" > "$project_root/test-results/coverage/api.log" 2>&1 &
server_pid=$!
cd "$project_root/frontend"
API_TARGET=http://127.0.0.1:8081 node node_modules/vite/bin/vite.js --host 127.0.0.1 --port 5174 --strictPort > "$project_root/test-results/coverage/vite.log" 2>&1 &
vite_pid=$!
for attempt in {1..30}; do
  kill -0 "$server_pid" "$vite_pid"
  if curl --fail --silent http://127.0.0.1:8081/api/health >/dev/null && curl --fail --silent http://127.0.0.1:5174/ >/dev/null; then break; fi
  sleep 1
done
curl --fail --silent http://127.0.0.1:8081/api/health >/dev/null
curl --fail --silent http://127.0.0.1:5174/ >/dev/null
kill -0 "$server_pid" "$vite_pid"
COVERAGE_DIR="$project_root/test-results/coverage/browser" TEST_BASE_URL=http://127.0.0.1:5174 node node_modules/@playwright/test/cli.js test "$@"
